"""Shared helpers for set-B agents (quote builder, scheduler, social
creator, reporting, compliance guard). Stdlib only.

Adapts to both state-store shapes in play:
  - core.state.State: get(business, key, default) / set(business, key, value)
    / append_log(business, event-dict)
  - plain test fakes: get(key, default) / set(key, value) / append_log(str)

Guard: core.guard.check_outbound is the real guard when importable; the
ctx["guard"] callable (draft-dict contract from agents._common) is used
as a second check where a draft dict applies.
"""
import datetime
import json
import os

AI_LABEL_PHRASES = (
    "built by ai",
    "made by ai",
    "ai built",
    "powered by ai",
    "generated by ai",
    "ai-generated",
    "ai generated",
    "created by ai",
)
