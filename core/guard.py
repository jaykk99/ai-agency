"""Outbound guard for the 50-agent AI agency.

Pure functions, no I/O, unit-testable.

Standing rules enforced here:
- Business email only from that business's own inbox (enforced by callers
  via the business config; this module enforces recipient/content rules).
- No info@ sends, ever.
- Never contact Integrity Roofing (integrityroofinginc.ca).
- Never put an AI label ('built by AI', 'made by AI', ...) in public copy.
- Bnb Media outreach only to Airbnb hosts / people posting houses on
  listing sites (source_tag must be 'airbnb' or 'listing').
- Phone 204-972-0325 on every non-Instagram public post: missing phone is
  a WARNING reason only, never a failure. Bnb copy carries no phone, so
  the phone warning is skipped for bnb-media.
- Money moves / bookings / anything charging Jay are always held.
"""

import re

PHONE = "204-972-0325"

INFO_LOCAL = "info"

BLOCKED_DOMAIN = "integrityroofinginc.ca"
BLOCKED_NAME = "integrity roofing"

AI_LABEL_PHRASES = (
    "built by ai",
    "made by ai",
    "ai built",
    "powered by ai",
    "generated by ai",
)

BNB_ALLOWED_SOURCE_TAGS = ("airbnb", "listing")

# Actions that always count as money moves and must be held for Jay's tap.
MONEY_ACTION_KEYWORDS = (
    "charge",
    "book",
    "pay",
    "payment",
    "move-money",
    "move money",
    "purchase",
    "buy",
    "transfer",
    "invoice",
    "spend",
)


def _slug(business):
    """Return the business slug from a config dict, a plain slug, or None."""
    if business is None:
        return None
    if isinstance(business, dict):
        return business.get("slug")
    return str(business)


def _phone(business):
    if isinstance(business, dict):
        return business.get("phone")
    return None


def check_outbound(business, recipient, subject, body, channel,
                   source_tag=None):
    """Check an outbound message before it may be sent.

    Args:
        business: business config dict (with 'slug' and 'phone') or slug str.
        recipient: destination email address / handle.
        subject: message subject (may be "" for non-email channels).
        body: message body / post copy.
        channel: 'email', 'facebook', 'post', 'instagram', 'sms', ...
        source_tag: lead source tag ('airbnb' | 'listing' | ...). Required
            for bnb-media email outreach.

    Returns:
        (ok, reasons): ok is False when a hard rule fails. Reasons holds
        failure reasons and also 'warning: ...' entries for the phone rule,
        which never fail the check on their own.
    """
    reasons = []
    recipient = (recipient or "").strip()
    subject = subject or ""
    body = body or ""
    channel = (channel or "").strip().lower()
    slug = _slug(business)
    combined = (subject + "\n" + body).lower()
    recip_lower = recipient.lower()

    # 1. No info@ sends, ever (case-insensitive, any info@ address).
    if recip_lower.startswith("info@"):
        reasons.append("recipient is an info@ address (info@ sends are banned)")

    # 2. Never contact Integrity Roofing.
    if recip_lower.endswith("@" + BLOCKED_DOMAIN) or \
            BLOCKED_DOMAIN in recip_lower:
        reasons.append("recipient domain is integrityroofinginc.ca "
                       "(Integrity Roofing must never be contacted)")
    if BLOCKED_NAME in combined or BLOCKED_DOMAIN in combined:
        reasons.append("message mentions Integrity Roofing "
                       "(Integrity Roofing must never be contacted)")

    # 3. No AI-label phrases in public copy.
    body_lower = body.lower()
    for phrase in AI_LABEL_PHRASES:
        if phrase in body_lower or phrase in subject.lower():
            reasons.append("copy contains AI-label phrase: %r" % phrase)

    # 4. Bnb Media: outreach only to Airbnb hosts / listing posters.
    if slug == "bnb-media" and channel == "email":
        if source_tag not in BNB_ALLOWED_SOURCE_TAGS:
            reasons.append(
                "bnb-media outreach requires source_tag 'airbnb' or "
                "'listing' (got %r)" % (source_tag,))

    # 5. Phone rule: warning only, never a failure. Skipped for bnb-media
    # (Bnb copy carries no phone) and for Instagram (DM call-to-action
    # replaces the phone line there).
    if channel in ("facebook", "post", "email") and slug != "bnb-media":
        phone = _phone(business)
        if phone and phone not in body:
            reasons.append(
                "warning: phone %s missing from copy" % phone)

    hard = [r for r in reasons if not r.startswith("warning:")]
    return (len(hard) == 0, reasons)


def check_money_action(action):
    """Return True when the action must be HELD for Jay's tap.

    Any charge / book / pay / move-money style action is always held.
    Non-money actions return False.
    """
    text = (action or "").strip().lower()
    if not text:
        return False
    for keyword in MONEY_ACTION_KEYWORDS:
        if keyword in text:
            return True
    return False
