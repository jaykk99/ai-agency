class TestGuard(unittest.TestCase):
    def test_rejects_info_at(self):
        ok, reasons = check_outbound(GG, "Info@example.com", "Hi", CLEAN_BODY, "email")
        self.assertFalse(ok)
        self.assertTrue(any("info@" in r for r in reasons))

    def test_rejects_info_at_case_insensitive(self):
        ok, _ = check_outbound(GG, "INFO@somewhere.ca", "Hi", CLEAN_BODY, "email")
        self.assertFalse(ok)

    def test_rejects_integrity_roofing_recipient(self):
        ok, reasons = check_outbound(
            GG, "sales@integrityroofinginc.ca", "Hi", CLEAN_BODY, "email")
        self.assertFalse(ok)
        self.assertTrue(any("Integrity Roofing" in r for r in reasons))

    def test_rejects_integrity_roofing_mention(self):
        ok, _ = check_outbound(
            GG, "someone@example.com", "Partner?",
            "We should partner with Integrity Roofing on this.", "email")
        self.assertFalse(ok)

    def test_rejects_ai_label_phrases(self):
        for phrase in ("built by AI", "made by AI", "AI built",
                       "powered by AI", "generated by AI"):
            with self.subTest(phrase=phrase):
                ok, reasons = check_outbound(
                    GG, "lead@example.com", "Hi",
                    "Check out this video %s." % phrase, "facebook")
                self.assertFalse(ok)
                self.assertTrue(any("AI-label" in r for r in reasons))

    def test_rejects_bnb_without_source_tag(self):
        ok, reasons = check_outbound(
            BNB, "host@example.com", "Video for your listing",
            "We make walkthrough videos from your photos.", "email")
        self.assertFalse(ok)
        self.assertTrue(any("source_tag" in r for r in reasons))

    def test_accepts_bnb_with_airbnb_tag(self):
        ok, reasons = check_outbound(
            BNB, "host@example.com", "Video for your listing",
            "We make walkthrough videos from your photos.", "email",
            source_tag="airbnb")
        self.assertTrue(ok, reasons)

    def test_accepts_bnb_with_listing_tag(self):
        ok, reasons = check_outbound(
            BNB, "host@example.com", "Video for your listing",
            "We make walkthrough videos from your photos.", "email",
            source_tag="listing")
        self.assertTrue(ok, reasons)

    def test_accepts_clean_gg_email(self):
        ok, reasons = check_outbound(
            GG, "lead@example.com", "Gutter cleaning",
            CLEAN_BODY, "email")
        self.assertTrue(ok, reasons)

    def test_phone_missing_is_warning_not_failure(self):
        ok, reasons = check_outbound(
            GG, "lead@example.com", "Hi",
            "Gutter cleaning, free inspection.", "email")
        self.assertTrue(ok)
        self.assertTrue(any(r.startswith("warning:") for r in reasons))

    def test_phone_warning_skipped_for_bnb(self):
        ok, reasons = check_outbound(
            BNB, "host@example.com", "Video",
            "Walkthrough video from your photos.", "email",
            source_tag="airbnb")
        self.assertTrue(ok, reasons)
        self.assertFalse(any("warning:" in r for r in reasons))


