class TestState(unittest.TestCase):
    def test_get_set_roundtrip(self):
        with tempfile.TemporaryDirectory() as tmp:
            state = State(Path(tmp))
            self.assertIsNone(state.get("gutter-genie", "last_run"))
            self.assertEqual(state.get("gutter-genie", "missing", "dflt"), "dflt")
            state.set("gutter-genie", "last_run", "2026-11-16")
            state.set("gutter-genie", "count", 3)
            self.assertEqual(state.get("gutter-genie", "last_run"), "2026-11-16")
            self.assertEqual(state.get("gutter-genie", "count"), 3)
            # Persisted on disk under state/<slug>.json
            data = json.loads(
                (Path(tmp) / "state" / "gutter-genie.json").read_text())
            self.assertEqual(data["count"], 3)

    def test_append_log(self):
        with tempfile.TemporaryDirectory() as tmp:
            state = State(Path(tmp))
            state.append_log("gutter-genie", {"event": "sent", "n": 1})
            state.append_log("gutter-genie", {"event": "sent", "n": 2})
            lines = (Path(tmp) / "state" / "gutter-genie-log.jsonl") \
                .read_text().strip().splitlines()
            self.assertEqual(len(lines), 2)
            self.assertEqual(json.loads(lines[1])["n"], 2)
            self.assertIn("ts", json.loads(lines[0]))

    def test_state_root_named_state(self):
        with tempfile.TemporaryDirectory() as tmp:
            state = State(Path(tmp) / "state")
            state.set("bnb-media", "x", 1)
            self.assertEqual(state.get("bnb-media", "x"), 1)


class TestYamlLoader(unittest.TestCase):
    def test_bare_list(self):
        doc = parse_simple_yaml("- id: a\n  name: A\n- id: b\n  name: B\n")
        self.assertEqual([d["id"] for d in doc], ["a", "b"])

    def test_wrapped_dict_agents(self):
        text = ("agents:\n"
                "  - id: lead_researcher\n"
                "    name: Lead Researcher\n"
                "    business: shared\n"
                "    status: working\n"
                "    module: agents.lead_researcher\n"
                "  - id: reporting\n"
                "    name: Reporting\n"
                "    status: defined\n")
        doc = parse_simple_yaml(text)
        agents = unwrap_list(doc, "agents")
        self.assertEqual(len(agents), 2)
        self.assertEqual(agents[0]["module"], "agents.lead_researcher")
        self.assertEqual(agents[1]["status"], "defined")

    def test_multiline_scalars(self):
        # Folded quoted and plain scalars, as used in the real registry.
        text = ("agents:\n"
                "- id: ops-manager\n"
                "  name: Ops Manager\n"
                "  description: 'Owns the daily run across all 7 businesses: queues work,\n"
                "    watches agent health.'\n"
                "  escalation: Escalates to Jay when any agent is blocked,\n"
                "    or a queue stalls.\n"
                "  status: working\n"
                "  module: agents.ops_manager\n")
        agents = unwrap_list(parse_simple_yaml(text), "agents")
        self.assertEqual(len(agents), 1)
        self.assertEqual(agents[0]["status"], "working")
        self.assertEqual(agents[0]["module"], "agents.ops_manager")
        self.assertIn("watches agent health", agents[0]["description"])
        self.assertIn("or a queue stalls", agents[0]["escalation"])

    def test_wrapped_dict_businesses(self):
        text = ("businesses:\n"
                "  - slug: gutter-genie\n"
                "    name: Gutter Genie\n"
                "    phone: 204-972-0325\n"
                "    services:\n"
                "      - cleaning\n"
                "      - guards\n")
        doc = parse_simple_yaml(text)
        businesses = unwrap_list(doc, "businesses")
        self.assertEqual(businesses[0]["slug"], "gutter-genie")
        self.assertEqual(businesses[0]["services"], ["cleaning", "guards"])

    def test_load_yaml_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "registry.yaml"
            path.write_text("agents:\n  - id: x\n    status: defined\n")
            self.assertEqual(unwrap_list(load_yaml(path), "agents")[0]["id"], "x")


class TestSupervisor(unittest.TestCase):
    def _make_root(self, tmp, registry_text, businesses_text):
        root = Path(tmp)
        (root / "agents").mkdir()
        (root / "config").mkdir()
        (root / "agents" / "registry.yaml").write_text(registry_text)
        (root / "config" / "businesses.yaml").write_text(businesses_text)
        return root

    def test_plan_mode_for_defined_agent(self):
        registry = ("agents:\n"
                    "  - id: social_creator\n"
                    "    name: Social Creator\n"
                    "    business: shared\n"
                    "    role: makes posts\n"
                    "    description: Creates social posts.\n"
                    "    inputs: [photos, hooks]\n"
                    "    tools: [instagram]\n"
                    "    outputs: [drafts]\n"
                    "    escalation: Jay approves copy\n"
                    "    status: defined\n")
        businesses = ("businesses:\n"
                      "  - slug: gutter-genie\n"
                      "    name: Gutter Genie\n"
                      "    inbox: guttergeniewpg@gmail.com\n"
                      "    phone: 204-972-0325\n")
        with tempfile.TemporaryDirectory() as tmp:
            root = self._make_root(tmp, registry, businesses)
            sup = Supervisor(root=root)
            result = sup.run({"agent": "social_creator",
                              "business": "gutter-genie",
                              "task": {"mode": "daily"}},
                             dry_run=True, date="2026-11-16")
            self.assertEqual(result["status"], "planned")
            self.assertEqual(len(result["outputs"]), 1)
            plan = Path(result["outputs"][0])
            self.assertTrue(plan.exists())
            self.assertIn("Social Creator", plan.read_text())
            self.assertIn("2026-11-16", str(plan))
            # Run was logged.
            self.assertTrue((root / "runs" / "runs.jsonl").exists())

    def test_plan_mode_bare_list_registry(self):
        registry = ("- id: reporting\n"
                    "  name: Reporting\n"
                    "  business: shared\n"
                    "  status: defined\n")
        businesses = ("- slug: gutter-genie\n"
                      "  name: Gutter Genie\n"
                      "  phone: 204-972-0325\n")
        with tempfile.TemporaryDirectory() as tmp:
            root = self._make_root(tmp, registry, businesses)
            result = Supervisor(root=root).run(
                {"agent": "reporting", "business": "gutter-genie",
                 "task": {}}, date="2026-11-16")
            self.assertEqual(result["status"], "planned")

    def test_unknown_agent_is_error_not_crash(self):
        registry = "agents:\n  - id: reporting\n    status: defined\n"
        businesses = "businesses:\n  - slug: gutter-genie\n    name: Gutter Genie\n"
        with tempfile.TemporaryDirectory() as tmp:
            root = self._make_root(tmp, registry, businesses)
            result = Supervisor(root=root).run(
                {"agent": "nope", "business": "gutter-genie", "task": {}})
            self.assertEqual(result["status"], "error")
            self.assertIn("nope", result["summary"])

    def test_working_agent_missing_module_is_error_not_crash(self):
        registry = ("agents:\n"
                    "  - id: lead_researcher\n"
                    "    name: Lead Researcher\n"
                    "    business: shared\n"
                    "    status: working\n"
                    "    module: agents.does_not_exist_xyz\n")
        businesses = "businesses:\n  - slug: gutter-genie\n    name: Gutter Genie\n"
        with tempfile.TemporaryDirectory() as tmp:
            root = self._make_root(tmp, registry, businesses)
            result = Supervisor(root=root).run(
                {"agent": "lead_researcher", "business": "gutter-genie",
                 "task": {}}, date="2026-11-16")
            self.assertEqual(result["status"], "error")
            self.assertTrue(result["log"])

    def test_shared_business_runs_without_slug_lookup(self):
        registry = ("agents:\n"
                    "  - id: reporting\n"
                    "    name: Reporting\n"
                    "    business: shared\n"
                    "    status: defined\n")
        businesses = "businesses:\n  - slug: gutter-genie\n    name: Gutter Genie\n"
        with tempfile.TemporaryDirectory() as tmp:
            root = self._make_root(tmp, registry, businesses)
            result = Supervisor(root=root).run(
                {"agent": "reporting", "business": "shared", "task": {}},
                date="2026-11-16")
            self.assertEqual(result["status"], "planned")

    def test_missing_registry_is_error_not_crash(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            result = Supervisor(root=root).run(
                {"agent": "reporting", "business": "gutter-genie", "task": {}})
            self.assertEqual(result["status"], "error")
            self.assertIn("registry", result["summary"])


